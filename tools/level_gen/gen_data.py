"""Файлы данных аномалий (.tres) для районов и секций этапов Б.
Тексты Энциклопедии — из сюжетных документов человека; до '---' — что видно при наблюдении."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TYPES = {"DEATH": 0, "VANISH": 1, "STATUS_EFFECT": 2, "EVENT": 3}


def esc(t):
    return t.replace("\\", "\\\\").replace('"', '\\"')


def fmt(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, float):
        return repr(v)
    if isinstance(v, int):
        return str(v)
    return '"' + esc(v) + '"'


def write(id_, display, location, danger, params, punishment, observed, full, hint=""):
    lines = ['[gd_resource type="Resource" script_class="AnomalyData" format=3]', "",
             '[ext_resource type="Script" path="res://anomalies/base/anomaly_data.gd" id="1_data"]']
    if punishment:
        lines.append('[ext_resource type="Script" path="res://anomalies/base/punishment.gd" id="2_punishment"]')
        kind, extra = punishment if isinstance(punishment, tuple) else (punishment, "")
        lines += ["", '[sub_resource type="Resource" id="Resource_punishment"]', 'script = ExtResource("2_punishment")',
                  f"type = {TYPES[kind]}"]
        if extra:
            lines.append(f'status_id = &"{extra}"')
    lines += ["", "[resource]", 'script = ExtResource("1_data")', f'id = &"{id_}"', f'display_name = "{esc(display)}"',
              f'location = "{esc(location)}"', f"danger_level = {danger}", "params = {",
              ",\n".join(f'"{k}": {fmt(v)}' for k, v in sorted(params.items())), "}"]
    if punishment:
        lines.append('punishment = SubResource("Resource_punishment")')
    if hint:
        lines.append(f'guide_hint = "{esc(hint)}"')
    lines.append(f'encyclopedia_text = "{esc(observed)}\n---\n{esc(full)}"')
    open(os.path.join(ROOT, "data", id_ + ".tres"), "w").write("\n".join(lines) + "\n")


